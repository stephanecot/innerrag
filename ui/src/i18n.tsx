const DICTS: Record<Lang, Dict> = { fr, en };

const STORAGE = "innerrag.lang";

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE);
    if (saved === "fr" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

// Module-level language, so helpers called outside React (util.ts) format consistently.
// The provider keeps it in sync; components re-render through the context.
let current: Lang = initialLang();

export const getLang = () => current;
export const locale = (lang: Lang = current) => (lang === "fr" ? "fr-FR" : "en-US");

const numberFormats = new Map<string, Intl.NumberFormat>();
function format(lang: Lang, n: number, decimals?: number): string {
  const id = `${lang}:${decimals ?? ""}`;
  let nf = numberFormats.get(id);
  if (!nf) {
    nf = new Intl.NumberFormat(locale(lang), decimals === undefined ? undefined : { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
    numberFormats.set(id, nf);
  }
  return nf.format(n);
}

/** Integer-style number in the interface language ("1 234" / "1,234"). */
export const num = (n: number) => format(current, n);
/** Number with two decimals ("0,25" / "0.25"). */
export const num2 = (n: number) => format(current, n, 2);

export type Vars = Record<string, string | number>;

/** French: 0 and 1 are singular. English: only 1. */
const isOne = (lang: Lang, n: number) => (lang === "fr" ? Math.abs(n) < 2 : n === 1);

function lookup(lang: Lang, key: Key, vars?: Vars): string {
  const entry: string | Plural = DICTS[lang][key] ?? fr[key];
  if (typeof entry === "string") return entry;
  return isOne(lang, Number(vars?.n ?? 0)) ? entry.one : entry.other;
}

function translateIn(lang: Lang, key: Key, vars?: Vars): string {
  const text = lookup(lang, key, vars);
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => {
    const v = vars[name];
    return v === undefined ? m : typeof v === "number" ? format(lang, v) : v;
  });
}

/** Translation outside React components (formatting helpers, error messages). */
export const translate = (key: Key, vars?: Vars) => translateIn(current, key, vars);

export interface T {
  (key: Key, vars?: Vars): string;
  /** Same, with React nodes in the placeholders (links, <code>, <strong>…). */
  rich: (key: Key, vars: Record<string, ReactNode>) => ReactNode;
}

function makeT(lang: Lang): T {
  const t = ((key: Key, vars?: Vars) => translateIn(lang, key, vars)) as T;
  t.rich = (key, vars) => {
    const parts = lookup(lang, key, vars as Vars).split(/\{(\w+)\}/);
    return parts.map((part, i) => {
      if (i % 2 === 0) return part;
      const v = vars[part];
      return <Fragment key={i}>{typeof v === "number" ? format(lang, v) : v}</Fragment>;
    });
  };
  return t;
}

const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({ lang: current, setLang: () => undefined });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current);
  const setLang = useCallback((next: Lang) => {
    current = next;
    try {
      localStorage.setItem(STORAGE, next);
    } catch {
      /* storage unavailable */
    }
    setLangState(next);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo(() => ({ lang, setLang }), [lang, setLang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): [Lang, (lang: Lang) => void] {
  const { lang, setLang } = useContext(LangContext);
  return [lang, setLang];
}

export function useT(): T {
  const { lang } = useContext(LangContext);
  return useMemo(() => makeT(lang), [lang]);
}
